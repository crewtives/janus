import { defineCommand } from "citty";
import { mkdtemp, mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { spawn } from "node:child_process";

import wrappedSampleMd from "../../docs/examples/wrapped-2025-sample.md" with { type: "text" };
// Bun types `.html` imports as `HTMLBundle` even with `type: "text"`. At runtime
// the import attribute wins and we get the file contents as a string; the cast
// just tells TypeScript what Bun is doing.
import wrappedSampleHtmlRaw from "../../docs/examples/wrapped-2025-sample.html" with { type: "text" };
const wrappedSampleHtml = wrappedSampleHtmlRaw as unknown as string;

