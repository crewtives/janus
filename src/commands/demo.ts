const README_DEMO = `# Janus demo vault

This is a *synthetic* vault generated by \`janus demo\`. Nothing here reflects a
real user — the projects (\`kepler\`, \`helios\`, \`atlas\`) are made-up, the dates
are fixed (2025-09-19), the prose is hand-written to illustrate Janus's voice,
and the Wrapped is the deterministic-renderer sample shipped in the repo.

A real Janus install:

- writes to your Obsidian vault (\`obsidianVault\` in \`config.local.json\`),
- uses \`claude -p\` (Claude Code, headless) to synthesize prose from your actual
  git history and Claude Code session transcripts,
- runs every night via \`launchd\` or \`systemd-user\`,
- exposes itself as an MCP server so other agents can query it.

To set that up: \`janus init\`.

## What's in this demo

\`\`\`
${"."}
├── README.md                            ← this file
├── Wrapped/
│   ├── Wrapped-2025.md                  ← yearly Wrapped, deterministic mode
│   └── Wrapped-2025.html                ← same data, HTML rendering
├── Projects/
│   ├── kepler/pulse/2025-09-19--kepler.md
│   └── helios/pulse/2025-09-19--helios.md
└── Timeline/
    └── Daily/2025-09-19.md
\`\`\`

Open \`Wrapped/Wrapped-2025.html\` in a browser to see the flagship artifact. A
real run produces longer prose (LLM-generated rather than deterministic), but
the structure is identical.
`;

export default defineCommand({
  meta: {
    name: "demo",
    description: "Materialize a synthetic vault with sample pulses + the deterministic Wrapped — no Obsidian, no Claude Max required.",
  },
  args: {
    "open": {
      type: "boolean",
      description: "Open the Wrapped HTML in the default browser after generating.",
      default: true,
    },
    "out": {
      type: "string",
      description: "Output directory. Default: a fresh tmpdir.",
    },
  },
  async run({ args }) {
    const outOverride = args.out as string | undefined;
    const out = outOverride
      ? outOverride
      : await mkdtemp(join(tmpdir(), "janus-demo-"));

    await mkdir(join(out, "Wrapped"), { recursive: true });
    await mkdir(join(out, "Projects", "kepler", "pulse"), { recursive: true });
    await mkdir(join(out, "Projects", "helios", "pulse"), { recursive: true });
    await mkdir(join(out, "Timeline", "Daily"), { recursive: true });

    await Promise.all([
      writeFile(join(out, "README.md"), README_DEMO),
      writeFile(join(out, "Wrapped", "Wrapped-2025.md"), wrappedSampleMd),
      writeFile(join(out, "Wrapped", "Wrapped-2025.html"), wrappedSampleHtml),
      writeFile(join(out, "Projects", "kepler", "pulse", "2025-09-19--kepler.md"), PULSE_KEPLER),
      writeFile(join(out, "Projects", "helios", "pulse", "2025-09-19--helios.md"), PULSE_HELIOS),
      writeFile(join(out, "Timeline", "Daily", "2025-09-19.md"), DAILY_ROLLUP),
    ]);

    const wrappedHtml = join(out, "Wrapped", "Wrapped-2025.html");

    console.log("");
    console.log(`Synthetic Janus vault written to:`);
    console.log(`  ${out}`);
    console.log("");
    console.log("Generated artifacts:");
    console.log("  Wrapped/Wrapped-2025.html       ← flagship, open in browser");
    console.log("  Wrapped/Wrapped-2025.md         ← Markdown version");
    console.log("  Projects/kepler/pulse/2025-09-19--kepler.md");
    console.log("  Projects/helios/pulse/2025-09-19--helios.md");
    console.log("  Timeline/Daily/2025-09-19.md");
    console.log("");

    if (args.open as boolean) {
      const opener = process.platform === "darwin"
        ? "open"
        : process.platform === "linux"
          ? "xdg-open"
          : null;
      if (opener) {
        try {
          spawn(opener, [wrappedHtml], { detached: true, stdio: "ignore" }).unref();
          console.log(`Opening Wrapped in your default browser...`);
        } catch {
          console.log(`Could not auto-open. Open this file manually:`);
          console.log(`  ${wrappedHtml}`);
        }
      } else {
        console.log(`Auto-open not supported on ${process.platform}. Open this file manually:`);
        console.log(`  ${wrappedHtml}`);
      }
    }

    console.log("");
    console.log("This is a synthetic demo — none of it is real activity.");
    console.log("To run Janus against your actual projects:");
    console.log("  janus init");
    console.log("");
  },
});
